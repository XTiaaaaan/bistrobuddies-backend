import { Router } from 'express';
import {
  readContactMessageId,
  readContactMessageListQuery,
  validateContactMessageReply,
  validateContactMessageStatusUpdate,
} from '../lib/validation';
import { requireAdmin, requireAuth } from '../middleware/auth';
import { asyncHandler } from '../middleware/error-handler';
import { rateLimit } from '../middleware/rate-limit';
import {
  addContactMessageReply,
  listContactMessages,
  updateContactMessageStatus,
} from '../services/contact-messages.service';

export const adminContactMessagesRouter = Router();

const adminGuard = [
  rateLimit({ name: 'admin-contact-messages', limit: 60, windowMs: 60_000 }),
  requireAuth,
  requireAdmin,
];

/**
 * GET /api/admin/contact-messages — list customer "Contact Us" messages
 * (admin only).
 *
 * Messages are returned newest first with `?status=NEW|READ|RESOLVED`
 * filtering and `?page`/`?pageSize` pagination (pageSize capped server-side).
 * Authorization reuses the project's standard admin guard: a verified
 * Firebase ID token plus `users/{uid}.role == 'admin'` read from Firestore on
 * every request — nothing from the request body is ever trusted. Firestore
 * access goes through the Admin SDK; clients remain denied by
 * `firestore.rules`.
 */
adminContactMessagesRouter.get(
  '/',
  ...adminGuard,
  asyncHandler(async (req, res) => {
    const query = readContactMessageListQuery(req.query);
    res.json(await listContactMessages(query));
  })
);

/**
 * PATCH /api/admin/contact-messages/:id/status — change a message's workflow
 * status (admin only).
 *
 * Accepts only `{ "status": "READ" | "RESOLVED" }`; `NEW` is the
 * server-assigned initial status and is rejected. Only `status` and
 * `updatedAt` are written — the customer's submission and `createdAt` can
 * never be edited through this endpoint. Unknown ids return
 * `404 contact_message_not_found`.
 */
adminContactMessagesRouter.patch(
  '/:id/status',
  ...adminGuard,
  asyncHandler(async (req, res) => {
    const messageId = readContactMessageId(req.params['id'] ?? '');
    const status = validateContactMessageStatusUpdate(req.body);
    res.json(await updateContactMessageStatus(messageId, status));
  })
);

/**
 * POST /api/admin/contact-messages/:id/replies — append an administrator's
 * reply to a customer message (admin only).
 *
 * Same admin guard as the list/status endpoints: a verified Firebase ID
 * token plus `users/{uid}.role == 'admin'` read server-side on every
 * request — a client-provided admin identity is never trusted. Only `reply`
 * is read from the body; `senderRole` and timestamps are generated by the
 * server, and an unknown id returns `404 contact_message_not_found`. A
 * successful reply on a `NEW` message moves it to `READ`; `RESOLVED` is
 * never automatic (see `addContactMessageReply`).
 */
adminContactMessagesRouter.post(
  '/:id/replies',
  ...adminGuard,
  asyncHandler(async (req, res) => {
    const messageId = readContactMessageId(req.params['id'] ?? '');
    const input = validateContactMessageReply(req.body);
    const result = await addContactMessageReply(messageId, input.reply);
    res.status(201).json(result);
  })
);
